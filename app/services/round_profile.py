"""轮次画像：同一份 JD + 简历，技术面和 HR 面要看的根本不是一回事。

C3（能力-证据矩阵）与 C4（问题链）原本只有一套提示词，输入只有「JD 能力项 + 简历」，
于是 HR 面也照着 JD 的技术能力项出题 —— HR 判不了「分布式事务」，也不关心，
他关心的是这个人稳不稳定、要多少钱、为什么走、什么时候能来。

改法不是把 HR 该问什么写死让模型照抄，而是**换一套评价坐标系**：
- 技术面（r1/r2）：坐标系 = JD 核心能力项（沿用岗位方定的说法与权重）
- HR 面（hr）：坐标系 = 六项 HR 通用维度 + 按简历补最多 2 项

HR 维度放在这里而不是写进 prompt 字符串，是因为**矩阵与问题链必须用同一套口径**：
矩阵说要考察「稳定性」，问题链却按「技术深度」出题，那两个步骤就对不上，
面试官会在 Step2 看到一堆跟 Step1 无关的题目。
"""
from __future__ import annotations

ROUND_R1 = "r1"
ROUND_R2 = "r2"
ROUND_HR = "hr"

# 进工作台的轮次类型（v1.26 删掉 offer 轮后，三种轮次全部进工作台）
INTERVIEW_ROUND_TYPES = (ROUND_R1, ROUND_R2, ROUND_HR)


def is_hr_round(round_type: str | None) -> bool:
    return str(round_type or "").strip().lower() == ROUND_HR


# ---------------------------------------------------------------- HR 维度


# （维度名，这一项到底要看什么）
# 六项是 HR 面的最小完备集：少了「到岗约束」会漏掉 offer 前才发现来不了的情况，
# 少了「薪资匹配」则是把最能谈崩的一项留到口头 offer 阶段才摊开。
HR_DIMENSIONS: list[tuple[str, str]] = [
    (
        "稳定性与任职持久度",
        "每段任职时长、跳槽频率、空窗期，判断能不能长期干下去",
    ),
    (
        "抗压能力与情绪管理",
        "高压项目、需求反复、线上故障、高强度排期下的真实表现与恢复方式",
    ),
    (
        "薪资预期与匹配度",
        "期望区间是否落在岗位预算内，构成（固定 / 浮动 / 股权）能否对齐",
    ),
    (
        "职业动机与离职原因",
        "为什么离开上一家、为什么选我们，动机是否自洽而非单纯逃离",
    ),
    (
        "文化契合与协作方式",
        "与上级、跨部门的协作偏好，能否适配本团队的管理节奏与沟通方式",
    ),
    (
        "到岗时间与入职约束",
        "最快到岗时间，以及竞业限制、违约金、试用期、 relocation 等现实约束",
    ),
]


def hr_dimension_lines() -> str:
    return "\n".join(f"{i}. {name}（{hint}）" for i, (name, hint) in enumerate(HR_DIMENSIONS, 1))


def hr_dimension_names() -> list[str]:
    return [name for name, _ in HR_DIMENSIONS]


# ---------------------------------------------------------------- HR 合规红线


# HR 面是合规风险最高的环节：想问「能不能长期干」很容易滑向「打算什么时候生孩子」，
# 想问「要多少钱」很容易滑向「你现在拿多少 / 家里有没有房贷」。
# 所以红线不是写在文档里让人自觉，而是**每次生成都喂给模型**。
HR_REDLINES: list[str] = [
    "不得追问或暗示婚育计划、是否有孩子、何时生育",
    "不得评价或追问年龄、户籍、民族、宗教、健康状况与残疾",
    "薪资只问**期望区间与构成**，不得追问当前薪资明细、家庭收入或负债（房贷等）",
    "稳定性要从**过往任职事实**（时长、离职原因、项目周期）去问，不从个人生活状况去推断",
    "到岗与入职约束只能问客观事实（竞业、通知期、签证），不得以此施压透露隐私",
]


def hr_redline_lines() -> str:
    return "\n".join(f"- {x}" for x in HR_REDLINES)
